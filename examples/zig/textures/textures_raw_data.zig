const std = @import("std");
const rl = @import("raylib");

pub fn main() !void {
    // Initialization
    const screen_width = 800;
    const screen_height = 450;

    rl.initWindow(screen_width, screen_height, "raylib [textures] example - raw data");
    defer rl.closeWindow(); // Close window and OpenGL context

    // NOTE: Textures MUST be loaded after Window initialization (OpenGL context is required)

    // Load RAW image data (512x512, 32bit RGBA, no file header)
    const fudesumi_raw = try rl.loadImageRaw("resources/fudesumi.raw", 384, 512, .uncompressed_r8g8b8a8, 0);
    const fudesumi = try rl.loadTextureFromImage(fudesumi_raw); // Upload CPU (RAM) image to GPU (VRAM)
    defer rl.unloadTexture(fudesumi); // Texture unloading
    rl.unloadImage(fudesumi_raw); // Unload CPU (RAM) image data

    // Generate a checked texture by code
    const im_width = 960;
    const im_height = 480;

    // Pixels data (Color type), owned here: the image below only borrows it,
    // so it is freed with the allocator rather than with UnloadImage()
    const allocator = std.heap.c_allocator;
    const pixels = try allocator.alloc(rl.Color, im_width * im_height);
    defer allocator.free(pixels);

    for (0..im_height) |y| {
        for (0..im_width) |x| {
            pixels[y * im_width + x] = if ((x / 32 + y / 32) % 2 == 0) .orange else .gold;
        }
    }

    // Load pixels data into an image structure and create texture
    // NOTE: We can assign pixels directly to data because Color is R8G8B8A8
    // data structure defining that pixelformat, format must be set properly
    const checked_im: rl.Image = .{
        .data = pixels.ptr,
        .width = im_width,
        .height = im_height,
        .format = .uncompressed_r8g8b8a8,
        .mipmaps = 1,
    };

    const checked = try rl.loadTextureFromImage(checked_im);
    defer rl.unloadTexture(checked); // Texture unloading

    rl.setTargetFPS(60); // Set our game to run at 60 frames-per-second

    // Main game loop
    while (!rl.windowShouldClose()) { // Detect window close button or ESC key
        // Draw
        rl.beginDrawing();
        defer rl.endDrawing();

        rl.clearBackground(.ray_white);

        rl.drawTexture(checked, screen_width / 2 - @divTrunc(checked.width, 2), screen_height / 2 - @divTrunc(checked.height, 2), rl.fade(.white, 0.5));
        rl.drawTexture(fudesumi, 430, -30, .white);

        rl.drawText("CHECKED TEXTURE ", 84, 85, 30, .brown);
        rl.drawText("GENERATED by CODE", 72, 148, 30, .brown);
        rl.drawText("and RAW IMAGE LOADING", 46, 210, 30, .brown);

        rl.drawText("(c) Fudesumi sprite by Eiden Marsal", 310, screen_height - 20, 10, .brown);
    }
}
